export type MuiIconName = keyof typeof muiIconMap;
export type MuiVariant = "outlined" | "rounded" | "sharp" | "twotone";

export interface MuiIconResolution extends MuiIconTarget {
  /** The base MUI name, e.g. `Search` for `SearchOutlined`. */
  name: string;
  /** The MUI variant that was stripped, if any. */
  variant?: MuiVariant;
}

// `Outline` is the legacy spelling still exported by MUI before v9 (`DeleteOutline`).
const VARIANT_SUFFIX = /(Outlined|Outline|Rounded|Sharp|TwoTone)$/;
const hasOwn = (name: string) => Object.hasOwn(muiIconMap, name);

/**
 * Resolves an `@mui/icons-material` module name to its replacements. An exact match wins; otherwise
 * one variant suffix (`Outlined`, legacy `Outline`, `Rounded`, `Sharp`, `TwoTone`) is stripped. Returns `undefined`
 * for names that are unknown or deliberately unmapped.
 */
export function resolveMuiIcon(muiName: string): MuiIconResolution | undefined {
  if (hasOwn(muiName)) return { name: muiName, ...muiIconMap[muiName as MuiIconName] };
  const match = VARIANT_SUFFIX.exec(muiName);
  if (!match) return undefined;
  const base = muiName.slice(0, -match[0].length);
  if (!base || !hasOwn(base)) return undefined;
  return {
    name: base,
    variant: (match[1] === "Outline" ? "outlined" : (match[1] ?? "").toLowerCase()) as MuiVariant,
    ...muiIconMap[base as MuiIconName],
  };
}
