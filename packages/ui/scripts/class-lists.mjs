// Pure helpers for scripts/build-classes.mjs, kept free of file access so they can be unit-tested
// (class-lists.test.mjs).
//
// Each entry ships a class list (dist/classes/<entry>.css) holding one `@source inline(...)` rule
// with exactly the Tailwind classes the entry's JS uses, chunks included. An app imports the lists
// for the components it uses, so Tailwind generates CSS for those and nothing else.

import { relativeImports, resolveImport } from "./dist-rules.mjs";

/**
 * Every file an entry reaches through relative imports, the entry itself and shared chunks
 * included. `read(file)` returns a file's code (paths relative to dist/), or undefined when the
 * file does not exist.
 */
export function reachableFiles(entryFile, read) {
  const seen = new Set();
  const queue = [entryFile];
  while (queue.length > 0) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    const code = read(file);
    if (code === undefined) continue;
    seen.add(file);
    for (const specifier of relativeImports(code)) queue.push(resolveImport(file, specifier));
  }
  return seen;
}

// `@source inline()` expands braces (`{a,b}`) and the string is double-quoted, so a class holding
// either would be mangled or end the string. None of ours do; fail loudly if one ever appears.
const UNSAFE = /[{}"\\]/;

/** The stylesheet for one class list: a header comment and one `@source inline(...)` rule. */
export function classListCss(label, classes) {
  const unsafe = classes.filter((c) => UNSAFE.test(c));
  if (unsafe.length > 0) {
    throw new Error(`${label}: cannot inline ${unsafe.map((c) => `"${c}"`).join(", ")}`);
  }
  const sorted = [...new Set(classes)].sort();
  return [
    `/* @azmr/ui class list: ${label}. Generated by scripts/build-classes.mjs; do not edit. */`,
    sorted.length === 0 ? "" : `@source inline("${sorted.join(" ")}");`,
    "",
  ].join("\n");
}
