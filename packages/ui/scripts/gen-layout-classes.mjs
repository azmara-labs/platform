// Generates src/components/layout/responsive.ts: the responsive Tailwind class tables used by
// Stack (direction), Grid (cols) and GridItem (span).
//
//   node scripts/gen-layout-classes.mjs && pnpm biome check --write src/components/layout
//
// Tailwind only generates classes it can see spelled out in full in the source, so
// `${prefix}grid-cols-${n}` built at runtime would silently produce no CSS. The tables are
// therefore written out as literals. responsive.test.ts recomputes them and fails on any drift.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

export const BREAKPOINTS = ["base", "sm", "md", "lg", "xl", "2xl"];
const prefix = (bp) => (bp === "base" ? "" : `${bp}:`);
const NUMBERS = Array.from({ length: 12 }, (_, i) => i + 1);

export function expectedTables() {
  const direction = {};
  const cols = {};
  const span = {};
  for (const bp of BREAKPOINTS) {
    const p = prefix(bp);
    direction[bp] = { row: `${p}flex-row`, column: `${p}flex-col` };
    cols[bp] = Object.fromEntries(NUMBERS.map((n) => [n, `${p}grid-cols-${n}`]));
    span[bp] = {
      ...Object.fromEntries(NUMBERS.map((n) => [n, `${p}col-span-${n}`])),
      full: `${p}col-span-full`,
    };
  }
  return { direction, cols, span };
}

function source() {
  const { direction, cols, span } = expectedTables();
  const table = (name, value) =>
    `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`;
  return [
    "// Generated by scripts/gen-layout-classes.mjs. Do not edit by hand.",
    "// Tailwind needs these class names spelled out in full to generate their CSS.",
    "",
    `export const BREAKPOINTS = ${JSON.stringify(BREAKPOINTS)} as const;`,
    "export type Breakpoint = (typeof BREAKPOINTS)[number];",
    "",
    table("DIRECTION_CLASSES", direction),
    table("COLS_CLASSES", cols),
    table("SPAN_CLASSES", span),
  ].join("\n");
}

if (
  import.meta.url === `file://${process.argv[1].replaceAll("\\", "/")}` ||
  process.argv[1]?.endsWith("gen-layout-classes.mjs")
) {
  const target = join(import.meta.dirname, "..", "src", "components", "layout", "responsive.ts");
  writeFileSync(target, source());
  console.log(`wrote ${target}`);
}
